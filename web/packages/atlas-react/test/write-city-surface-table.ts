/**
 * Writes `tests/fixtures/city-surface-table.json`: the walk surface the page stands a person on,
 * sampled over the street surfaces of three baked tiles, which `tests/test_city_surface.py` holds the
 * city grammar's integer surface (`exulanica/grammar/grammars/city/surface.py`) to.
 *
 * The heights are the page's own: each tile's `nav_envelope`, read by `composedSupport`, exactly as
 * `tile-navigation.ts` stands a person on a generated tile. The points are the centroids of every
 * fourth triangle each street record draws into the envelope, floored to whole millimetres.
 *
 * The three tiles are tess's conformance fixture, tile (0, 0) of a small town, and tile (0, 0) of the
 * same small town made on the land recipes' default land (rolling), where its kerb lines climb and fall
 * and its footways ramp into mitred corners. The towns' documents are generated by the Python grammar,
 * so they are written first and passed in, from `web/`:
 *
 *     PYTHONPATH=.. ../.venv/bin/python ../tests/test_city_surface.py /tmp/town-0-0.json /tmp/land-0-0.json
 *     pnpm exec tsx packages/atlas-react/test/write-city-surface-table.ts /tmp/town-0-0.json /tmp/land-0-0.json
 *
 * `test/city-surface-table.test.ts` holds the conformance rows equal to a fresh bake, and the
 * Python test holds the town's document to the digest written here.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { absoluteVertices, bakeTile, decodeOwd } from '@exulanica/loom-tess/core';
import { composedSupport } from '../src/playcanvas/generated-tile/tile-navigation.js';

// Relative to web/, where the suite and this writer run.
export const CONFORMANCE_FIXTURE = 'packages/loom-tess/test/fixtures/tile-conformance.json';
export const SURFACE_TABLE = '../tests/fixtures/city-surface-table.json';
/** The street kinds whose drawn surfaces are sampled. */
const STREET_KINDS = new Set(['city.curb_edge', 'city.street_segment', 'city.junction']);
/** Every how many of a record's envelope triangles a point is taken from. */
const EVERY = 4;

/** One sample: plan x and y in millimetres, the page's height in micrometres, the drawing record's kind. */
export type SurfaceRow = readonly [number, number, number, string];

const sha256 = async (bytes: Uint8Array): Promise<string> => createHash('sha256').update(bytes).digest('hex');

/** The page's walk surface over the street surfaces of one baked container. */
export function surfaceRows(container: Uint8Array): SurfaceRow[] {
  const decoded = decodeOwd(container);
  const envelope = decoded.projections.find((projection) => projection.header.name === 'nav_envelope');
  if (envelope === undefined) throw new Error('the container carries no nav_envelope');
  const { surface } = composedSupport([{ tile: 'the tile', projection: envelope }]);
  const vertices = absoluteVertices(envelope);
  const at = (vertex: number, axis: number): number => vertices[vertex * 3 + axis]!;
  const rows: SurfaceRow[] = [];
  for (const entry of envelope.header.entries) {
    if (entry.state !== 'drawn') continue;
    const kind = decoded.header.records[entry.record]!.kind;
    if (!STREET_KINDS.has(kind)) continue;
    for (let triangle = 0; triangle < entry.triangle_count; triangle += EVERY) {
      const corner = (entry.first_triangle + triangle) * 3;
      const [a, b, c] = [envelope.index[corner]!, envelope.index[corner + 1]!, envelope.index[corner + 2]!];
      const x = Math.floor((at(a, 0) + at(b, 0) + at(c, 0)) / 3);
      const y = Math.floor((at(a, 1) + at(b, 1) + at(c, 1)) / 3);
      const sample = surface.sample(x / 1000, -y / 1000);
      if (sample === null) continue;
      rows.push([x, y, Math.round(sample.height * 1_000_000), kind]);
    }
  }
  return rows;
}

/** The conformance fixture baked now, and its rows. */
export async function conformanceRows(): Promise<SurfaceRow[]> {
  return surfaceRows((await bakeTile(new Uint8Array(readFileSync(CONFORMANCE_FIXTURE)), sha256)).container);
}

async function main(townDocument: string, landTownDocument: string): Promise<void> {
  const town = new Uint8Array(readFileSync(townDocument));
  const landTown = new Uint8Array(readFileSync(landTownDocument));
  const table = {
    profile: 'exulanica.city-surface-table/v1',
    tiles: [
      {
        name: 'conformance',
        document: CONFORMANCE_FIXTURE,
        document_sha256: await sha256(new Uint8Array(readFileSync(CONFORMANCE_FIXTURE))),
        rows: await conformanceRows(),
      },
      {
        name: 'small_town',
        town: { preset: 'small_town', world_id: 'city-surface-table', tile: [0, 0] },
        document_sha256: await sha256(town),
        rows: surfaceRows((await bakeTile(town, sha256)).container),
      },
      {
        name: 'town_on_land',
        town: { preset: 'small_town', world_id: 'city-surface-table', tile: [0, 0], land: 'rolling' },
        document_sha256: await sha256(landTown),
        rows: surfaceRows((await bakeTile(landTown, sha256)).container),
      },
    ],
  };
  writeFileSync(SURFACE_TABLE, `${JSON.stringify(table)}\n`);
  for (const tile of table.tiles) process.stdout.write(`${tile.name}: ${tile.rows.length} rows\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1]!).href) await main(process.argv[2]!, process.argv[3]!);
