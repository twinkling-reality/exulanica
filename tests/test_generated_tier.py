"""The generated tier: what it records, and the four things it can never do.

The claim this file defends is narrow and total. Content a world model imagined may be stored,
labelled, and read back with its full provenance, and it may never become evidence, satisfy a
reconstruction gate, promote a rung, or reach a consumer that did not ask for it by name.
"""

from __future__ import annotations

import hashlib
import json
import typing
import uuid

import pytest
from exulanica.errors import EpistemicViolation
from exulanica.graph import read_snapshot
from exulanica.graph.world_read import world_read_bundle
from exulanica.ingest.generated_scene import record_generated_scene
from exulanica.ingest.stages import STAGES, stage
from exulanica.reconstruction.generated import (
    GENERATED_SCENE_KIND,
    GENERATED_SCENE_STAGE,
    ConditioningDigest,
    GeneratedSceneReceipt,
    GenerationModel,
    generation_input_digest,
)
from exulanica.reconstruction.scene_gate import (
    SceneGateInputs,
    SceneReceipt,
    validate_scene_gate_decision,
)

from test_world_read_bundle import _published_scene

_SEAM = "The counter continues past the last photograph; everything beyond it is imagined."


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _receipt(bundle_sha256: str, **overrides) -> GeneratedSceneReceipt:
    fields = {
        "model": GenerationModel(
            provider="example-labs", model_id="worldgen", model_version="2026.09"
        ),
        "prompt_sha256": _sha("continue the counter"),
        "conditioning": (ConditioningDigest(role="world-read-bundle", sha256=bundle_sha256),),
        "container": "sog/1",
        "content_sha256": _sha("the generated bytes"),
        "byte_size": 4096,
        "seam": _SEAM,
    }
    fields.update(overrides)
    return GeneratedSceneReceipt(**fields)  # type: ignore[arg-type]


@pytest.fixture
def generated(repository, tmp_path):
    """One real scene, and one generation recorded against its current bundle."""
    store, _captures, scene_id = _published_scene(repository, tmp_path, registered=3, spacing=5)
    envelope = world_read_bundle(repository.connection, repository.workspace_id, scene_id, store)
    assert envelope is not None
    receipt = _receipt(envelope["bundle"]["recorded_sha256"])
    record = record_generated_scene(
        repository,
        store,
        scene_id=scene_id,
        receipt=receipt,
        expected_recorded_sha256=envelope["bundle"]["recorded_sha256"],
    )
    assert record.inserted
    return store, scene_id, receipt, record


# -- the stage itself ---------------------------------------------------------------------


def test_the_stage_is_registered_and_declares_itself_non_deterministic():
    spec = stage(GENERATED_SCENE_STAGE)
    assert spec.output_kind == GENERATED_SCENE_KIND
    assert spec.deterministic is False
    assert spec.params["tier"] == "generated"
    assert spec.params["citable"] is False
    assert spec.params["promotes_rung"] is False


def test_the_stage_carries_no_model_role():
    """Deliberate, and pinned so it is not "fixed" later.

    A role names a slot the platform routes through its own reviewed model manifest. The model
    here is supplied per generation. Setting a role would also change the set of model-bearing
    stages that the digest-bound record docs/evaluation/2026-09-05-unblocked-goal-d.json is
    asserted against, and amending a retained record so a new field fits is backwards.
    """
    assert stage(GENERATED_SCENE_STAGE).model_role is None
    roles = sorted(key for key, spec in STAGES.items() if spec.model_role is not None)
    assert roles == ["depth", "vision"]


def test_a_model_swap_produces_a_different_artifact_identity():
    """The scene-subject equivalent of the binding digest, and the reason it exists."""
    bundle = _sha("bundle")
    first = _receipt(bundle)
    same = _receipt(bundle)
    newer = _receipt(
        bundle,
        model=GenerationModel(
            provider="example-labs", model_id="worldgen", model_version="2026.10"
        ),
    )
    other_prompt = _receipt(bundle, prompt_sha256=_sha("a different instruction"))
    other_bundle = _receipt(_sha("a different bundle"))

    assert generation_input_digest(first) == generation_input_digest(same)
    assert generation_input_digest(first) != generation_input_digest(newer)
    assert generation_input_digest(first) != generation_input_digest(other_prompt)
    assert generation_input_digest(first) != generation_input_digest(other_bundle)


def test_a_generation_that_names_no_conditioning_is_refused():
    with pytest.raises(ValueError, match="conditioned on"):
        _receipt(_sha("bundle"), conditioning=())


def test_a_generation_that_names_no_world_read_bundle_is_refused():
    with pytest.raises(ValueError, match="exactly one world-read-bundle"):
        _receipt(
            _sha("bundle"),
            conditioning=(ConditioningDigest(role="point_map", sha256=_sha("a map")),),
        )


def test_a_generation_without_a_seam_is_refused():
    """A generated surface a viewer cannot tell from a photographed one is the whole failure."""
    with pytest.raises(ValueError, match="seam"):
        _receipt(_sha("bundle"), seam="looks fine")


def test_a_container_the_renderer_cannot_validate_is_refused():
    with pytest.raises(ValueError, match="container"):
        _receipt(_sha("bundle"), container="mystery/1")


