async def phase_knee(built: Stack, spec: dict[str, Any]) -> dict[str, Any]:
    """Closed-loop small reads at each concurrency, spread over the workspaces."""
    steps = []
    for concurrency in spec["concurrency"]:
        observed = Observed()
        clients = Clients(built, observed, spec.get("photo", {"width": 64, "height": 48}))
        tokens = [grant.token for grant in built.grants]
        until = time.monotonic() + spec["seconds"]
        with Sampler(built) as sampler:
            await asyncio.gather(
                *(
                    clients.reads_closed_loop(tokens[index % len(tokens)], until, "knee")
                    for index in range(concurrency)
                )
            )
        await clients.close()
        summary = observed.summary()["reads"]
        steps.append(
            {
                "concurrency": concurrency,
                "seconds": spec["seconds"],
                "throughput_per_second": round(
                    sum(1 for r in observed.reads if r["status"] == 200) / spec["seconds"], 1
                ),
                **summary,
                "server": summarise_samples(sampler.samples, sampler.idle),
            }
        )
        print(
            f"knee c={concurrency}: {steps[-1]['throughput_per_second']}/s "
            f"p95={summary['admitted_ms'].get('p95')} refused={summary['refused_ms'].get('count', 0)}",
            flush=True,
        )
    return {"steps": steps}


async def phase_mixed(built: Stack, spec: dict[str, Any], name: str) -> dict[str, Any]:
    """Open-loop reads, held streams, and watched uploads, in every workspace at once."""
    per = spec["per_workspace"]
    held = open_running_batches(built, per.get("held_streams", 0))
    observed = Observed()
    clients = Clients(built, observed, spec["photo"])
    until = time.monotonic() + spec["seconds"]
    watchers: list[asyncio.Task] = []
    tasks = []
    holding: list[asyncio.Task] = []
    for grant in built.grants:
        for batch in held[grant.token]:
            holding.append(
                asyncio.ensure_future(clients.stream(grant.token, batch, name, until=until))
            )
        if per.get("reads_per_second"):
            tasks.append(clients.reads_open_loop(grant.token, per["reads_per_second"], until, name))
        if per.get("uploads_every_seconds"):
            tasks.append(
                clients.uploads_every(
                    grant.token,
                    per["uploads_every_seconds"],
                    per["photos_per_upload"],
                    until,
                    name,
                    watchers,
                )
            )
    with Sampler(built) as sampler:
        await asyncio.gather(*tasks, asyncio.sleep(max(0.0, until - time.monotonic())))
        # A held stream on a batch that never ends sends only heartbeats; it is left here.
        for task in holding:
            task.cancel()
        await asyncio.gather(*holding, return_exceptions=True)
        drain_until = time.monotonic() + spec.get("drain_seconds", 120)
        # The watched uploads finish after the load stops: their outcome is part of the result.
        while watchers and time.monotonic() < drain_until and not all(w.done() for w in watchers):
            await asyncio.sleep(0.5)
        for watcher in watchers:
            if not watcher.done():
                watcher.cancel()
        await asyncio.gather(*watchers, return_exceptions=True)
    close_held_batches(built)
    await clients.close()
    return {
        "seconds": spec["seconds"],
        "per_workspace": per,
        "workspaces": len(built.grants),
        "clients": observed.summary(),
        "server": summarise_samples(sampler.samples, sampler.idle),
    }


def make_towns(built: Stack, spec: dict[str, Any]) -> list[dict[str, Any]]:
    """A generated town with a living society in each of the first ``towns`` workspaces."""
    import httpx

    towns = []
    for grant in built.grants[: spec["towns"]]:
        client = httpx.Client(
            base_url=built.base_url, headers={"Authorization": f"Bearer {grant.token}"}, timeout=300
        )
        started = time.monotonic()
        made = client.post(
            "/worlds/generated", json={"recipe": spec["recipe"], "title": "runtime capacity town"}
        )
        made.raise_for_status()
        entry = made.json()
        scope = {"world_id": entry["world_id"]}
        version = entry["authored_version_id"]
        society = client.post(
            f"/world/versions/{version}/society",
            params=scope,
            json={"region_id": "region:generated", "profile": spec["profile"]},
        )
        society.raise_for_status()
        towns.append(
            {
                "token": grant.token,
                "workspace": str(grant.workspace),
                "version": version,
                "scope": scope,
                "made_seconds": round(time.monotonic() - started, 2),
            }
        )
        client.close()
    return towns


def play_towns(built: Stack, towns: list[dict[str, Any]], speed: int) -> None:
    import httpx

    for town in towns:
        client = httpx.Client(
            base_url=built.base_url,
            headers={"Authorization": f"Bearer {town['token']}"},
            timeout=60,
        )
        control = f"/world/versions/{town['version']}/society/control"
        read = client.get(control, params=town["scope"])
        read.raise_for_status()
        pressed = client.put(
            control,
            params=town["scope"],
            json={"base_revision": read.json()["revision"], "mode": "playing", "speed": speed},
        )
        pressed.raise_for_status()
        client.close()


def town_ticks(built: Stack, towns: list[dict[str, Any]]) -> list[int]:
    import httpx

    ticks = []
    for town in towns:
        read = httpx.get(
            built.base_url + f"/world/versions/{town['version']}/society/control",
            params=town["scope"],
            headers={"Authorization": f"Bearer {town['token']}"},
            timeout=60,
        )
        ticks.append(read.json().get("current_tick", -1) if read.status_code == 200 else -1)
    return ticks


async def traffic_reads(
    clients: Clients, town: dict[str, Any], every: float, until: float, phase: str
) -> None:
    path = (
        f"/world/versions/{town['version']}/traffic?world_id={town['scope']['world_id']}&seconds=60"
    )
    while time.monotonic() < until:
        await clients.read(town["token"], path, phase + ":traffic")
        await asyncio.sleep(every)


async def phase_sharing(built: Stack, spec: dict[str, Any], name: str) -> dict[str, Any]:
    """The supported load again, beside towns the host plays and pages reading their traffic."""
    towns = await asyncio.to_thread(make_towns, built, spec)
    listed = json.dumps([town["workspace"] for town in towns])
    await asyncio.to_thread(built.stop_api)
    await asyncio.to_thread(
        built.start_api,
        EXULANICA_SOCIETY_CONTROL_WORKSPACES=listed,
        EXULANICA_SOCIETY_TICK_INTERVAL_MS=str(spec.get("base_tick_interval_ms", 8000)),
    )
    await asyncio.to_thread(play_towns, built, towns, spec["speed"])
    await asyncio.sleep(spec.get("warmup_seconds", 20))
    ticks_before = await asyncio.to_thread(town_ticks, built, towns)
    started = time.monotonic()
    traffic_observed = Observed()
    traffic_clients = Clients(built, traffic_observed, spec["photo"])
    until = time.monotonic() + spec["seconds"]
    readers = [
        asyncio.ensure_future(
            traffic_reads(traffic_clients, town, spec["traffic_every_seconds"], until, name)
        )
        for town in towns
    ]
    mixed = await phase_mixed(built, spec, name)
    await asyncio.gather(*readers)
    await traffic_clients.close()
    ticks_after = await asyncio.to_thread(town_ticks, built, towns)
    wall = time.monotonic() - started
    traffic = [r for r in traffic_observed.reads]
    return {
        **mixed,
        "towns": {
            "count": len(towns),
            "recipe": spec["recipe"],
            "profile": spec["profile"],
            "speed": spec["speed"],
            "base_tick_interval_ms": spec.get("base_tick_interval_ms", 8000),
            "made_seconds": [town["made_seconds"] for town in towns],
            "ticks_advanced": [
                after - before for before, after in zip(ticks_before, ticks_after, strict=True)
            ],
            "wall_seconds": round(wall, 1),
        },
        "traffic_reads": {
            "sent": len(traffic),
            "ms": spread([r["ms"] for r in traffic if r["status"] == 200]),
            "by_status": dict(
                sorted(
                    Counter(f"{r['status']} {r.get('code') or ''}".strip() for r in traffic).items()
                )
            ),
        },
    }


