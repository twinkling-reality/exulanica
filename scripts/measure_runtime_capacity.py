class Sampler:
    """A thread that reads the server's side every half second while a phase runs."""

    def __init__(self, built: Stack) -> None:
        self.built = built
        self.samples: list[dict[str, Any]] = []
        self.idle: list[float] = []
        self._stop = threading.Event()
        self._threads = [
            threading.Thread(target=self._run, daemon=True),
            threading.Thread(target=self._idle, daemon=True),
        ]

    def __enter__(self) -> Sampler:
        for thread in self._threads:
            thread.start()
        return self

    def __exit__(self, *_exc: object) -> None:
        self._stop.set()
        for thread in self._threads:
            thread.join(20)

    def _idle(self) -> None:
        while not self._stop.is_set():
            value = idle_share(5)
            if value is not None:
                self.idle.append(value)

    def _run(self) -> None:
        import httpx
        import psycopg

        with (
            psycopg.connect(self.built.owner_url, autocommit=True) as owner,
            httpx.Client(timeout=10) as client,
        ):
            last_ready = 0.0
            while not self._stop.is_set():
                started = time.monotonic()
                sample: dict[str, Any] = {"t": time.time()}
                rows = owner.execute(
                    "select usename, count(*) from pg_stat_activity "
                    "where datname = current_database() and backend_type = 'client backend' "
                    "and pid <> pg_backend_pid() group by usename"
                ).fetchall()
                sample["backends"] = {name or "?": int(count) for name, count in rows}
                jobs = owner.execute("select state, count(*) from job group by state").fetchall()
                sample["jobs"] = {state: int(count) for state, count in jobs}
                api = self.built.api
                if api is not None and api.poll() is None:
                    sample["api"] = _process(api.pid)
                health_started = time.monotonic()
                with contextlib.suppress(httpx.HTTPError):
                    health = client.get(self.built.base_url + "/healthz")
                    sample["healthz_ms"] = round((time.monotonic() - health_started) * 1000, 2)
                    sample["healthz_status"] = health.status_code
                if time.monotonic() - last_ready >= 1.0:
                    last_ready = time.monotonic()
                    ready_started = time.monotonic()
                    with contextlib.suppress(httpx.HTTPError, ValueError):
                        client.get(self.built.base_url + "/readyz")
                        sample["readyz_ms"] = round((time.monotonic() - ready_started) * 1000, 2)
                    # The counts are an operator's read, so they are asked for as one: a request
                    # like any other, which a full requests class may refuse (recorded as such).
                    with contextlib.suppress(httpx.HTTPError, ValueError):
                        counts = client.get(
                            self.built.base_url + "/operations/capacity",
                            headers={"Authorization": f"Bearer {self.built.grants[0].token}"},
                        )
                        if counts.status_code == 200:
                            document = counts.json()
                            # This read is itself an admitted request: counted out here.
                            document["classes"]["requests"]["in_flight"] -= 1
                            sample["capacity"] = document
                        else:
                            sample["capacity_refused"] = counts.status_code
                self.samples.append(sample)
                self._stop.wait(max(0.0, SAMPLE_SECONDS - (time.monotonic() - started)))


def _process(pid: int) -> dict[str, Any]:
    """Threads, resident memory and CPU share of one process, from ``ps``.

    ``ps -M`` prints a header and then one line per thread.
    """
    threads = subprocess.run(
        ["ps", "-M", "-p", str(pid)], capture_output=True, text=True
    ).stdout.splitlines()
    usage = subprocess.run(
        ["ps", "-o", "rss=,%cpu=", "-p", str(pid)], capture_output=True, text=True
    ).stdout.split()
    return {
        "threads": max(0, len([line for line in threads if line.strip()]) - 1),
        "rss_kib": int(usage[0]) if usage else None,
        "cpu_percent": float(usage[1]) if len(usage) > 1 else None,
    }


def summarise_samples(samples: list[dict[str, Any]], idle: list[float]) -> dict[str, Any]:
    def peak(path: list[str]) -> Any:
        values = []
        for sample in samples:
            value: Any = sample
            for key in path:
                value = value.get(key) if isinstance(value, dict) else None
            if isinstance(value, int | float):
                values.append(value)
        return max(values) if values else None

    backends = [sum(sample.get("backends", {}).values()) for sample in samples]
    by_role: dict[str, int] = defaultdict(int)
    for sample in samples:
        for role, count in sample.get("backends", {}).items():
            by_role[role] = max(by_role[role], count)
    queued = [sample.get("jobs", {}).get("queued", 0) for sample in samples]
    running = [sample.get("jobs", {}).get("running", 0) for sample in samples]
    healthz = [sample["healthz_ms"] for sample in samples if "healthz_ms" in sample]
    readyz = [sample["readyz_ms"] for sample in samples if "readyz_ms" in sample]
    capacity_peaks: dict[str, int] = {}
    for sample in samples:
        classes = (sample.get("capacity") or {}).get("classes", {})
        for name, counts in classes.items():
            capacity_peaks[name] = max(capacity_peaks.get(name, 0), counts.get("in_flight", 0))
    last_capacity = next(
        (sample["capacity"] for sample in reversed(samples) if sample.get("capacity")), None
    )
    return {
        "samples": len(samples),
        "backends_peak": max(backends) if backends else None,
        "backends_peak_by_role": dict(by_role),
        "api_threads_peak": peak(["api", "threads"]),
        "api_rss_kib_peak": peak(["api", "rss_kib"]),
        "api_cpu_percent_peak": peak(["api", "cpu_percent"]),
        "queued_jobs_peak": max(queued) if queued else None,
        "running_jobs_peak": max(running) if running else None,
        "queued_jobs_last": queued[-1] if queued else None,
        "healthz_ms": spread(healthz),
        "healthz_failures": sum(
            1 for sample in samples if sample.get("healthz_status") not in (200, None)
        )
        + sum(1 for sample in samples if "healthz_ms" not in sample),
        "readyz_ms": spread(readyz),
        "in_flight_peaks": capacity_peaks,
        "capacity_at_end": last_capacity,
        "idle_percent_during": {
            "samples": len(idle),
            "mean": round(statistics.fmean(idle), 1) if idle else None,
            "minimum": min(idle) if idle else None,
        },
    }


def spread(values: list[float]) -> dict[str, Any]:
    """Count, p50, p95, p99 and maximum of exact values, nearest-rank."""
    if not values:
        return {"count": 0}
    ordered = sorted(values)

    def rank(q: float) -> float:
        return round(ordered[min(len(ordered) - 1, max(0, math.ceil(q * len(ordered)) - 1))], 2)

    return {
        "count": len(ordered),
        "p50": rank(0.50),
        "p95": rank(0.95),
        "p99": rank(0.99),
        "max": round(ordered[-1], 2),
    }


