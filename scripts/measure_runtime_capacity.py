def open_running_batches(built: Stack, per_workspace: int) -> dict[str, list[str]]:
    """Batches that stay running, one per held stream: what a watched upload in progress costs.

    Written directly, labelled, with no job: nothing will close them, so a stream on one stays
    open and polls for the whole phase, which is the cost being measured.
    """
    import psycopg

    held: dict[str, list[str]] = {}
    with psycopg.connect(built.owner_url, autocommit=True) as owner:
        for grant in built.grants:
            held[grant.token] = [
                str(
                    owner.execute(
                        "insert into intake_batch (workspace_id, label) values (%s, %s) "
                        "returning batch_id",
                        (grant.workspace, "runtime capacity: held stream"),
                    ).fetchone()[0]
                )
                for _ in range(per_workspace)
            ]
    return held


def close_held_batches(built: Stack) -> None:
    import psycopg

    with psycopg.connect(built.owner_url, autocommit=True) as owner:
        owner.execute(
            "update intake_batch set status = 'cancelled', ended_at = now() "
            "where label = 'runtime capacity: held stream' and status = 'running'"
        )


