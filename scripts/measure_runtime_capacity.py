def _assert_tree() -> dict[str, Any]:
    """Refuse to measure anything but this tree, then name it: commit and uncommitted digest."""
    import exulanica

    resolved = Path(exulanica.__file__).resolve()
    if not resolved.is_relative_to(ROOT.resolve()):
        raise SystemExit(f"exulanica imports from {resolved}, not from {ROOT}; run from the tree")
    head = _git("rev-parse", "HEAD")
    diff = subprocess.run(
        ["git", "--no-optional-locks", "diff", "HEAD", "--binary"],
        capture_output=True,
        check=True,
        cwd=ROOT,
    ).stdout
    untracked = _git("ls-files", "--others", "--exclude-standard").split()
    digest = hashlib.sha256(diff)
    for name in sorted(untracked):
        digest.update(name.encode() + b"\0" + (ROOT / name).read_bytes())
    # What ran: the package and this harness, byte for byte, whatever happens to docs and tests.
    runtime = hashlib.sha256()
    for path in sorted(
        [
            *(ROOT / "exulanica").rglob("*.py"),
            *(ROOT / "exulanica").rglob("*.sql"),
            ROOT / "scripts/measure_runtime_capacity.py",
            ROOT / "pyproject.toml",
            ROOT / "uv.lock",
        ]
    ):
        runtime.update(str(path.relative_to(ROOT)).encode() + b"\0" + path.read_bytes())
    return {
        "head": head,
        "uncommitted_sha256": digest.hexdigest(),
        "runtime_sha256": runtime.hexdigest(),
        "changed_paths": sorted(set(_git("diff", "HEAD", "--name-only").split()) | set(untracked)),
    }


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", "--no-optional-locks", *args], capture_output=True, text=True, check=True, cwd=ROOT
    ).stdout.strip()


def _machine() -> dict[str, Any]:
    import importlib.metadata as metadata

    def sysctl(name: str) -> str:
        return subprocess.run(["sysctl", "-n", name], capture_output=True, text=True).stdout.strip()

    return {
        "system": platform.system(),
        "release": platform.release(),
        "cpu": sysctl("machdep.cpu.brand_string") if platform.system() == "Darwin" else None,
        "logical_cpus": os.cpu_count(),
        "memory_bytes": int(sysctl("hw.memsize") or 0) if platform.system() == "Darwin" else None,
        "python": platform.python_version(),
        "packages": {
            name: metadata.version(name)
            for name in ("fastapi", "starlette", "uvicorn", "anyio", "psycopg", "h11", "httpx")
        },
    }


def idle_share(seconds: int = IDLE_SAMPLE_SECONDS) -> float | None:
    """The CPU idle percentage over the next ``seconds``, from ``top``, or None off macOS."""
    if platform.system() != "Darwin":
        return None
    out = subprocess.run(
        ["top", "-l", "2", "-s", str(seconds), "-n", "0"], capture_output=True, text=True
    ).stdout
    lines = [line for line in out.splitlines() if line.startswith("CPU usage")]
    return float(lines[-1].split(",")[2].split("%")[0].strip()) if lines else None


def load_average() -> list[float]:
    return [round(value, 2) for value in os.getloadavg()]


def other_heavy_processes(limit: int = 8) -> list[dict[str, Any]]:
    """The busiest processes on the machine now, with their command's first word, for the record."""
    out = subprocess.run(
        ["ps", "-Ao", "pcpu=,pid=,comm="], capture_output=True, text=True
    ).stdout.splitlines()
    rows = []
    for line in out:
        parts = line.split(None, 2)
        if len(parts) == 3:
            with contextlib.suppress(ValueError):
                rows.append(
                    {"cpu": float(parts[0]), "pid": int(parts[1]), "command": Path(parts[2]).name}
                )
    return sorted(rows, key=lambda row: row["cpu"], reverse=True)[:limit]


# -- the stack --------------------------------------------------------------------------------


@dataclass
class Grant:
    workspace: uuid.UUID
    actor: uuid.UUID
    token: str


@dataclass
class Stack:
    """The database, the API process and the worker process, and how to reach each."""

    workload: dict[str, Any]
    run_dir: Path
    grants: list[Grant]
    owner_url: str = ""
    runtime_url: str = ""
    readonly_url: str = ""
    api: subprocess.Popen | None = None
    worker: subprocess.Popen | None = None
    extra_workers: list[subprocess.Popen] = field(default_factory=list)
    server: Any = None
    api_environment: dict[str, str] = field(default_factory=dict)

    @property
    def base_url(self) -> str:
        return f"http://127.0.0.1:{self.workload['ports']['api']}"

    def tokens(self) -> str:
        from exulanica.api.permissions import Permission

        return json.dumps(
            {
                grant.token: {
                    "workspace_id": str(grant.workspace),
                    "actor": str(grant.actor),
                    "permissions": [str(permission) for permission in Permission],
                }
                for grant in self.grants
            }
        )

    # database

    def start_database(self) -> None:
        sys.path.insert(0, str(ROOT / "scripts"))
        import test_postgres

        from exulanica.db.cli import provision
        from exulanica.db.migrate import provision_workspace
        from exulanica.db.roles import EXECUTOR_ROLE, RUNTIME_ROLE

        # Durable, as a deployment's server is: the harness default turns fsync off, which would
        # make every commit here cheaper than it is anywhere a person's data lives.
        test_postgres.SETTINGS.update(
            {"fsync": "on", "full_page_writes": "on", "max_connections": "100"}
        )
        test_postgres.sweep()
        server = test_postgres.Server(
            test_postgres.base_directory() / f"runtime-capacity-{os.getpid()}"
        )
        server.root.mkdir(parents=True)
        (server.root / "owner.pid").write_text(str(os.getpid()))
        self.server = server
        server.initialise()
        server.start(port=int(self.workload["ports"]["database"]))
        test_postgres.create_runtime_roles(server)
        self.owner_url = server.create_database("exulanica_runtime_capacity_test")
        previous = os.environ.get("EXULANICA_DATABASE_URL")
        os.environ["EXULANICA_DATABASE_URL"] = self.owner_url
        try:
            provision(io.StringIO())
        finally:
            if previous is None:
                os.environ.pop("EXULANICA_DATABASE_URL", None)
            else:
                os.environ["EXULANICA_DATABASE_URL"] = previous
        database = self.owner_url.rsplit("/", 1)[1]
        self.runtime_url = server.url(database, RUNTIME_ROLE)
        self.readonly_url = server.url(database, EXECUTOR_ROLE)
        import psycopg

        with psycopg.connect(self.owner_url, autocommit=True) as owner:
            for grant in self.grants:
                provision_workspace(owner, grant.workspace)

    # processes

    def environment(self, **extra: str) -> dict[str, str]:
        env = {
            key: value
            for key, value in os.environ.items()
            if not key.startswith("EXULANICA_") and key not in ("NEBIUS_API_KEY",)
        }
        env.update(
            {
                "EXULANICA_DATABASE_URL": self.runtime_url,
                "EXULANICA_READONLY_DATABASE_URL": self.readonly_url,
                "EXULANICA_DATA_DIR": str(self.run_dir / "data"),
                "EXULANICA_DERIVATIVE_WORKER": "off",
                "EXULANICA_API_TOKENS": self.tokens(),
                **{key: str(value) for key, value in self.workload.get("settings", {}).items()},
                **extra,
            }
        )
        return env

    def start_api(self, **extra: str) -> None:
        self.api_environment = self.environment(**extra)
        with open(self.run_dir / "api.log", "ab") as log:
            self.api = subprocess.Popen(
                [
                    str(ROOT / ".venv/bin/python"),
                    "-m",
                    "uvicorn",
                    "--factory",
                    "exulanica.api.app:create_app",
                    "--host",
                    "127.0.0.1",
                    "--port",
                    str(self.workload["ports"]["api"]),
                    "--no-access-log",
                    *self.workload.get("uvicorn_arguments", []),
                ],
                cwd=ROOT,
                env=self.api_environment,
                stdout=log,
                stderr=subprocess.STDOUT,
                start_new_session=True,
            )
        self.wait_ready()

    def wait_ready(self, timeout: float = 120.0) -> None:
        import httpx

        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if self.api is not None and self.api.poll() is not None:
                raise SystemExit(f"the API exited with {self.api.returncode}; see api.log")
            with contextlib.suppress(httpx.HTTPError):
                if httpx.get(self.base_url + "/readyz", timeout=5).json().get("ready"):
                    return
            time.sleep(0.5)
        raise SystemExit("the API did not become ready")

    def start_worker(self, name: str = "capacity-worker") -> subprocess.Popen:
        worker = self.workload["derivative_worker"]
        env = self.environment(
            EXULANICA_WORKSPACE_IDS=",".join(str(grant.workspace) for grant in self.grants)
        )
        with open(self.run_dir / f"{name}.log", "ab") as log:
            process = subprocess.Popen(
                [
                    str(ROOT / ".venv/bin/python"),
                    str(ROOT / "scripts/measure_runtime_capacity.py"),
                    "worker",
                    "--name",
                    name,
                    "--vision-seconds",
                    str(worker["vision_seconds"]),
                    "--poll-seconds",
                    str(worker["poll_seconds"]),
                ],
                cwd=ROOT,
                env=env,
                stdout=log,
                stderr=subprocess.STDOUT,
                start_new_session=True,
            )
        if self.worker is None:
            self.worker = process
        else:
            self.extra_workers.append(process)
        return process

    def stop_api(self, sig: int = signal.SIGTERM, timeout: float = 30.0) -> float:
        started = time.monotonic()
        if self.api is not None and self.api.poll() is None:
            self.api.send_signal(sig)
            try:
                self.api.wait(timeout)
            except subprocess.TimeoutExpired:
                self.api.kill()
                self.api.wait()
        return time.monotonic() - started

    def close(self) -> None:
        for process in [self.api, self.worker, *self.extra_workers]:
            if process is not None and process.poll() is None:
                with contextlib.suppress(ProcessLookupError):
                    os.kill(process.pid, signal.SIGCONT)
                process.terminate()
                try:
                    process.wait(20)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
        if self.server is not None:
            sys.path.insert(0, str(ROOT / "scripts"))
            import test_postgres

            test_postgres.remove_test_server(self.server)


@contextlib.contextmanager
def stack(workload: dict[str, Any], run_dir: Path) -> Iterator[Stack]:
    for port in workload["ports"].values():
        with socket.socket() as probe:
            if probe.connect_ex(("127.0.0.1", int(port))) == 0:
                raise SystemExit(f"port {port} is already in use; the run needs slot 1 free")
    grants = [
        Grant(uuid.uuid4(), uuid.uuid4(), f"capacity-{index}-{uuid.uuid4().hex}")
        for index in range(int(workload["workspaces"]))
    ]
    built = Stack(workload=workload, run_dir=run_dir, grants=grants)
    try:
        built.start_database()
        built.start_api()
        built.start_worker()
        yield built
    finally:
        built.close()


# -- the scripted worker ----------------------------------------------------------------------


def worker_main(argv: list[str]) -> int:
    """The production derivative worker with a vision model that sleeps and answers the same."""
    parser = argparse.ArgumentParser(prog="measure_runtime_capacity.py worker")
    parser.add_argument("--name", default="capacity-worker")
    parser.add_argument("--vision-seconds", type=float, default=1.0)
    parser.add_argument("--poll-seconds", type=float, default=1.0)
    args = parser.parse_args(argv)

    from exulanica.db.session import Database
    from exulanica.env import resolve_data_dir
    from exulanica.ingest.privacy import authorize_synthetic_capture, record_synthetic_exemption
    from exulanica.ingest.vision import VisionObservation, VisionResult
    from exulanica.ingest.worker import MINIMUM_LEASE_SECONDS, DerivativeWorker
    from exulanica.ingest.worker_command import parse_workspaces
    from exulanica.store.local import LocalContentAddressedStore

    observation = {
        "scene_description": "A generated test pattern of coloured blocks.",
        "objects": [{"label": "block", "salience": "primary", "confidence": "high", "box": None}],
        "legible_text": [],
        "proposed_place": None,
    }

    class ScriptedVision:
        """Answers after ``--vision-seconds``, as a model would, and never leaves the machine."""

        model_id = "MiniMaxAI/MiniMax-M3"

        def observe(self, *, image_bytes: bytes, media_type: str) -> VisionResult:
            time.sleep(args.vision_seconds)
            return VisionResult(
                observation=VisionObservation.model_validate(observation),
                payload=dict(observation),
                model_id=self.model_id,
                model_ref={"provider": "scripted", "model_id": self.model_id, "endpoint": "none"},
                cost={"input_tokens": 0, "output_tokens": 0, "usd_estimate": "0"},
                attempts=1,
                tried=(self.model_id,),
                latency_ms=int(args.vision_seconds * 1000),
            )

    class ScreeningWorker(DerivativeWorker):
        """Records each capture's synthetic screening before its job runs, then runs it as is."""

        def _run_job(self, repository, claimed, outcome, keeper):  # type: ignore[override]
            for capture_id in claimed.capture_ids:
                if repository.latest_privacy_screening(capture_id) is None:
                    with contextlib.suppress(Exception):
                        authorization = authorize_synthetic_capture(
                            repository,
                            capture_id=capture_id,
                            actor=uuid.UUID(int=1),
                            generator_manifest=GENERATOR,
                            authorization_scope={"purpose": "runtime capacity measurement"},
                        )
                        record_synthetic_exemption(
                            repository, authorization_id=authorization.authorization_id
                        )
            return super()._run_job(repository, claimed, outcome, keeper)

    environ = os.environ
    worker = ScreeningWorker(
        Database.from_env(environ),
        LocalContentAddressedStore(resolve_data_dir(environ) / "blobs"),
        parse_workspaces([], environ),
        vision=ScriptedVision(),
        name=args.name,
        poll_seconds=args.poll_seconds,
        lease_seconds=MINIMUM_LEASE_SECONDS,
    )
    stop = threading.Event()
    for received in (signal.SIGINT, signal.SIGTERM):
        signal.signal(received, lambda _n, _f: stop.set())
    worker.start()
    print(
        json.dumps({"event": "worker_started", "name": args.name, "pid": os.getpid()}), flush=True
    )
    while not stop.wait(0.5):
        if not worker.alive:
            print(json.dumps({"event": "worker_died", "error": worker.last_error}), flush=True)
            return 1
    worker.stop(timeout=30)
    return 0


