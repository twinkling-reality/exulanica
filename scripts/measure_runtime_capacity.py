#!/usr/bin/env python3
"""Measure how much concurrent work one API process accepts, and what it answers past that.

    .exulanica/bin/quiet-slot .venv/bin/python scripts/measure_runtime_capacity.py run \
        --workload scripts/runtime_capacity_workload.json --phases knee,supported,overload \
        --out RECORD.json
    .venv/bin/python scripts/measure_runtime_capacity.py run \
        --workload scripts/runtime_capacity_workload.json --phases chaos --out RECORD.json

**The product runs as it is deployed.** A private PostgreSQL 18 made for the run and removed after
(``scripts/test_postgres.py``), provisioned by ``exulanica-db``'s own ``provision``; the API as the
image starts it, ``uvicorn --factory exulanica.api.app:create_app``, from this tree (the module path
is asserted before anything is measured), connecting as the non-owner runtime role with the
read-only executor role configured; ``EXULANICA_DERIVATIVE_WORKER=off`` and a dedicated derivative
worker process, as ``compose.yaml`` runs them. Every setting the workload names reaches the API
through its environment.

**One thing is scripted, and it is labelled.** The dedicated worker is the production
``DerivativeWorker`` (claims, leases, retries, ledger) with a vision model that sleeps a declared
time and returns a fixed observation, so a derivative job costs what a model call would cost in
time and nothing in money. It also records the synthetic screening each capture needs before the
vision stage runs; every photograph here is generated by this script. No request leaves the
machine.

**The workload** is a JSON file (``scripts/runtime_capacity_workload.json``) naming the ports, the
workspaces, the capacity settings and the phases. A record names the source tree and its digest,
the machine, the settings, the load and every observation, so another run on another tree is
comparable line by line. Phases:

*   ``knee``: small reads by closed loops at rising concurrency, for latency against concurrency.
*   ``supported``, ``overload``, ``sharing``: open-loop small reads, held progress streams, uploads
    whose progress is watched to its end, and (``sharing``) inhabited worlds played by the host.
*   ``chaos``: a client killed while it holds streams, requests cancelled mid-body, a stalled
    upload body, a held table lock, the derivative worker killed and paused past its lease, and the
    API restarted mid-stream. Each checks that slots come back, that every watched batch reaches one
    terminal outcome, that no event id arrives twice on one subscription, and that no workspace sees
    another's batch.

Server-side samples every half second: PostgreSQL client backends by role, the API process's
threads, resident memory and CPU, the derivative queue by state, and the admission counts
``/readyz`` reports. The machine's idle CPU share is read before and after (``top``, ten seconds)
and every five seconds during a run. Timing phases belong inside ``.exulanica/bin/quiet-slot``;
an overload phase needs root's saturation exception first.
"""

