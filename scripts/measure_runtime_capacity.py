def capacity(built: Stack) -> dict[str, Any]:
    import httpx

    return httpx.get(
        built.base_url + "/operations/capacity",
        headers={"Authorization": f"Bearer {built.grants[-1].token}"},
        timeout=10,
    ).json()


def wait_for(condition, timeout: float, step: float = 0.1) -> float | None:
    """Seconds until ``condition()`` holds, or None when it did not within ``timeout``."""
    started = time.monotonic()
    while time.monotonic() - started < timeout:
        with contextlib.suppress(Exception):
            if condition():
                return round(time.monotonic() - started, 3)
        time.sleep(step)
    return None


def in_flight(built: Stack, name: str) -> int:
    """In flight in ``name`` now, not counting the capacity read itself, which is a request."""
    held = capacity(built)["classes"][name]["in_flight"]
    return held - 1 if name == "requests" else held


def hold_main(argv: list[str]) -> int:
    """A client that opens streams and holds them until it is killed."""
    parser = argparse.ArgumentParser(prog="measure_runtime_capacity.py hold")
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--stream", action="append", required=True, help="TOKEN:BATCH")
    args = parser.parse_args(argv)
    held = []
    for pair in args.stream:
        token, batch = pair.split(":", 1)
        connection = socket.create_connection(("127.0.0.1", args.port))
        connection.sendall(
            f"GET /formation/{batch} HTTP/1.1\r\nHost: 127.0.0.1\r\n"
            f"Authorization: Bearer {token}\r\nAccept: text/event-stream\r\n\r\n".encode()
        )
        held.append(connection)
    print(json.dumps({"event": "holding", "streams": len(held)}), flush=True)
    while True:
        time.sleep(1)


def raw_request(
    built: Stack, head: str, body: bytes = b"", *, close_after: float | None = None
) -> socket.socket:
    connection = socket.create_connection(("127.0.0.1", int(built.workload["ports"]["api"])))
    connection.sendall(head.encode() + body)
    if close_after is not None:
        time.sleep(close_after)
        connection.close()
    return connection


def chaos(built: Stack, spec: dict[str, Any]) -> dict[str, Any]:
    results: dict[str, Any] = {}
    token = built.grants[0].token
    other = built.grants[1].token

    # 1. A client killed while it holds streams: its slots come back. Streams spread over
    # workspaces, each within its share, so the whole count is admitted.
    share = int(built.workload["settings"].get("EXULANICA_API_WORKSPACE_STREAMS", 8))
    wanted = spec["killed_client_streams"]
    holders = built.grants[: max(1, math.ceil(wanted / share))]
    held_by = open_running_batches(built, share)
    pairs = [f"{grant.token}:{batch}" for grant in holders for batch in held_by[grant.token]][
        :wanted
    ]
    child = subprocess.Popen(
        [
            str(ROOT / ".venv/bin/python"),
            str(ROOT / "scripts/measure_runtime_capacity.py"),
            "hold",
            "--port",
            str(built.workload["ports"]["api"]),
            *[part for pair in pairs for part in ("--stream", pair)],
        ],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        text=True,
        start_new_session=True,
    )
    opened = wait_for(lambda: in_flight(built, "streams") >= len(pairs), 30)
    killed_at = time.monotonic()
    os.kill(child.pid, signal.SIGKILL)
    child.wait()
    released = wait_for(lambda: in_flight(built, "streams") == 0, 30)
    results["killed_client"] = {
        "streams": len(pairs),
        "workspaces": len(holders),
        "all_admitted_after_s": opened,
        "released_after_kill_s": released,
        "kill_to_check_s": round(time.monotonic() - killed_at, 3),
    }
    close_held_batches(built)

    # 2. Requests cancelled mid-body, and a read cancelled before its answer: slots come back.
    upload = raw_request(
        built,
        "POST /intake HTTP/1.1\r\nHost: 127.0.0.1\r\n"
        f"Authorization: Bearer {token}\r\nContent-Type: multipart/form-data; boundary=x\r\n"
        "Content-Length: 10485760\r\n\r\n",
        b'--x\r\nContent-Disposition: form-data; name="files"; filename="a.jpg"\r\n'
        b"Content-Type: image/jpeg\r\n\r\n" + b"0" * 65536,
    )
    upload_held = wait_for(lambda: in_flight(built, "uploads") == 1, 10)
    upload.close()
    upload_released = wait_for(lambda: in_flight(built, "uploads") == 0, 30)
    read = raw_request(
        built,
        "POST /world/versions HTTP/1.1\r\nHost: 127.0.0.1\r\n"
        f"Authorization: Bearer {token}\r\nContent-Type: application/json\r\n"
        "Content-Length: 100000\r\n\r\n",
        b"{",
    )
    read_held = wait_for(lambda: in_flight(built, "requests") == 1, 10)
    read.close()
    read_released = wait_for(lambda: in_flight(built, "requests") == 0, 30)
    results["cancelled"] = {
        "upload_in_flight_after_s": upload_held,
        "upload_released_after_close_s": upload_released,
        "request_in_flight_after_s": read_held,
        "request_released_after_close_s": read_released,
    }

    # 3. Stalled upload bodies hold the uploads class until their idle deadline, then 408.
    stalled = []
    for _ in range(int(built.workload["settings"].get("EXULANICA_API_UPLOADS", 2))):
        stalled.append(
            raw_request(
                built,
                "POST /intake HTTP/1.1\r\nHost: 127.0.0.1\r\n"
                f"Authorization: Bearer {token}\r\nContent-Type: multipart/form-data; boundary=x\r\n"
                "Content-Length: 1048576\r\n\r\n",
                b"--x\r\n",
            )
        )
    full = wait_for(lambda: in_flight(built, "uploads") >= len(stalled), 10)
    import httpx

    refused_upload = httpx.post(
        built.base_url + "/intake",
        headers={"Authorization": f"Bearer {other}"},
        files=[("files", ("x.jpg", jpeg(64, 48, 1), "image/jpeg"))],
        timeout=30,
    )
    started = time.monotonic()
    answers = []
    for connection in stalled:
        connection.settimeout(60)
        with contextlib.suppress(OSError):
            answers.append(connection.recv(4096).split(b"\r\n", 1)[0].decode())
        connection.close()
    results["stalled_bodies"] = {
        "held": len(stalled),
        "class_full_after_s": full,
        "other_upload_meanwhile": [refused_upload.status_code, refused_upload.json().get("code")],
        "answered": answers,
        "answered_after_s": round(time.monotonic() - started, 2),
        "released_after_s": wait_for(lambda: in_flight(built, "uploads") == 0, 30),
    }

    # 4. A held table lock: reads that need it wait, the rest are refused fast, streams carry on.
    results["held_lock"] = asyncio.run(_held_lock(built, spec))

    # 5. The worker killed mid-batch, then restarted: the batch reaches one outcome.
    results["worker_killed"] = asyncio.run(_worker_interrupted(built, spec, pause=False))

    # 6. The worker paused past its lease while another reclaims its job (concurrent writers).
    results["worker_paused"] = asyncio.run(_worker_interrupted(built, spec, pause=True))

    # 7. The API restarted mid-stream: clients resume and reach the same outcome.
    results["api_restarted"] = asyncio.run(_api_restarted(built, spec))
    return results


async def _held_lock(built: Stack, spec: dict[str, Any]) -> dict[str, Any]:
    import psycopg

    observed = Observed()
    clients = Clients(built, observed, {"width": 64, "height": 48})
    held = open_running_batches(built, 4)
    until = time.monotonic() + spec["lock_seconds"] + 20
    holding = [
        asyncio.ensure_future(clients.stream(grant.token, batch, "held_lock", until=until))
        for grant in built.grants[:2]
        for batch in held[grant.token]
    ]
    tasks = [clients.reads_open_loop(grant.token, 5, until, "held_lock") for grant in built.grants]

    def lock() -> None:
        time.sleep(5)
        with psycopg.connect(built.owner_url) as connection, connection.transaction():
            connection.execute("lock table intake_batch in access exclusive mode")
            time.sleep(spec["lock_seconds"])

    locker = threading.Thread(target=lock)
    with Sampler(built) as sampler:
        locker.start()
        await asyncio.gather(*tasks)
        for task in holding:
            task.cancel()
        await asyncio.gather(*holding, return_exceptions=True)
        await asyncio.to_thread(locker.join)
    close_held_batches(built)
    await clients.close()
    released = wait_for(
        lambda: all(c["in_flight"] == 0 for c in capacity(built)["classes"].values()), 60
    )
    return {
        "lock_seconds": spec["lock_seconds"],
        "clients": observed.summary(),
        "server": summarise_samples(sampler.samples, sampler.idle),
        "all_released_after_s": released,
    }


async def _worker_interrupted(built: Stack, spec: dict[str, Any], *, pause: bool) -> dict[str, Any]:
    """Kill (or pause) the worker once a watched batch has started, and follow it to its end."""
    import psycopg

    observed = Observed()
    clients = Clients(built, observed, spec["photo"])
    token = built.grants[2].token
    batch = await clients.upload(token, spec["interrupted_batch_photos"], "interrupted")
    watcher = asyncio.create_task(
        clients.stream(token, batch, "interrupted", watch=True, max_seconds=900)
    )
    worker = built.worker
    started_capture = await asyncio.to_thread(
        wait_for,
        lambda: _ledger_events(built, batch) >= 2,
        120,
    )
    moment = time.monotonic()
    if pause:
        os.kill(worker.pid, signal.SIGSTOP)
    else:
        os.kill(worker.pid, signal.SIGKILL)
        worker.wait()
    replacement = built.start_worker(
        name="capacity-worker-" + ("reclaimer" if pause else "restarted")
    )
    resumed = None
    if pause:
        # Past its lease, the paused worker's job is reclaimed; then it wakes and writes on.
        await asyncio.sleep(75)
        os.kill(worker.pid, signal.SIGCONT)
        resumed = round(time.monotonic() - moment, 1)
    record = await watcher
    with psycopg.connect(built.owner_url, autocommit=True) as owner:
        ledger = [
            str(row[0])
            for row in owner.execute(
                "select pe.event_id from pipeline_event pe join pipeline_run pr on pr.run_id = pe.run_id "
                "where pr.batch_id = %s order by pe.event_id",
                (batch,),
            ).fetchall()
        ]
        batch_row = owner.execute(
            "select status, ended_at from intake_batch where batch_id = %s", (batch,)
        ).fetchone()
        jobs = owner.execute(
            "select state, attempts from job where batch_id = %s", (batch,)
        ).fetchall()
        delivery = [
            {"worker": worker, "event": event, "attempt": attempt, "at": at.isoformat()}
            for worker, event, attempt, at in owner.execute(
                "select e.worker_id, e.event_type, e.attempt, e.occurred_at "
                "from derivative_job_event e join job j on j.job_id = e.job_id "
                "where j.batch_id = %s and e.event_type <> 'lease_renewed' "
                "order by e.occurred_at, e.event_id",
                (batch,),
            ).fetchall()
        ]
    # Every ledger event the projection would stream, against what this subscription received.
    replay = await clients.stream(token, batch, "replay", watch=False)
    await clients.close()
    if not pause:
        built.worker = replacement
        built.extra_workers.remove(replacement)
    streamed = set(record["events"])
    replayed = set(replay["events"])
    return {
        "photos": spec["interrupted_batch_photos"],
        "interrupted_after_ledger_events": started_capture,
        "paused_for_s": resumed,
        "terminal_streamed": record["terminal"],
        "terminal_replayed": replay["terminal"],
        "batch": {"status": batch_row[0], "ended": batch_row[1] is not None},
        "jobs": [{"state": state, "attempts": attempts} for state, attempts in jobs],
        "delivery_events": delivery,
        "subscription_attempts": [a.get("status") for a in record["attempts"]],
        "duplicates": record["duplicates"],
        "foreign": record["foreign"],
        "streamed_events": len(streamed),
        "replayed_events": len(replayed),
        "missed_by_live_stream": sorted(replayed - streamed),
        "ledger_events": len(ledger),
    }


def _ledger_events(built: Stack, batch: str) -> int:
    import psycopg

    with psycopg.connect(built.owner_url, autocommit=True) as owner:
        return int(
            owner.execute(
                "select count(*) from pipeline_event pe join pipeline_run pr on pr.run_id = pe.run_id "
                "where pr.batch_id = %s and pe.stage_key in ('rendition', 'vision')",
                (batch,),
            ).fetchone()[0]
        )


async def _api_restarted(built: Stack, spec: dict[str, Any]) -> dict[str, Any]:
    observed = Observed()
    clients = Clients(built, observed, spec["photo"])
    tokens = [grant.token for grant in built.grants[3:5]]
    batches = [
        await clients.upload(token, spec["interrupted_batch_photos"], "restart") for token in tokens
    ]
    watchers = [
        asyncio.create_task(clients.stream(t, b, "restart", watch=True, max_seconds=600))
        for t, b in zip(tokens, batches, strict=True)
    ]
    await asyncio.sleep(3)
    stopped = await asyncio.to_thread(built.stop_api, signal.SIGKILL)
    down_at = time.monotonic()
    await asyncio.to_thread(built.start_api)
    back = round(time.monotonic() - down_at, 2)
    records = await asyncio.gather(*watchers)
    await clients.close()
    return {
        "stopped_in_s": round(stopped, 2),
        "back_after_s": back,
        "batches": [
            {
                "terminal": record["terminal"],
                "attempts": [a.get("status") for a in record["attempts"]],
                "duplicates": record["duplicates"],
                "foreign": record["foreign"],
            }
            for record in records
        ],
    }


