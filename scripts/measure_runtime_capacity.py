def run_main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="measure_runtime_capacity.py run")
    parser.add_argument(
        "--workload", type=Path, default=ROOT / "scripts/runtime_capacity_workload.json"
    )
    parser.add_argument("--phases", default="knee,supported")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--idle-gate", type=float, default=70.0)
    parser.add_argument("--saturation-approved", action="store_true")
    parser.add_argument(
        "--announce",
        type=Path,
        help="a coordination file the start and end of a saturation phase are appended to",
    )
    args = parser.parse_args(argv)

    workload = json.loads(args.workload.read_text())
    if workload.get("profile") != WORKLOAD_PROFILE:
        raise SystemExit(f"{args.workload} is not a {WORKLOAD_PROFILE} file")
    phases = [name.strip() for name in args.phases.split(",") if name.strip()]
    unknown = [name for name in phases if name not in workload["phases"] and name != "chaos"]
    if unknown:
        raise SystemExit(f"the workload names no phase {unknown}")
    if (
        any(workload["phases"].get(name, {}).get("saturation") for name in phases)
        and not args.saturation_approved
    ):
        raise SystemExit(
            "an overload phase needs root's saturation exception: pass --saturation-approved"
        )

    record: dict[str, Any] = {
        "profile": PROFILE,
        "started_at": dt.datetime.now(dt.UTC).isoformat(timespec="seconds"),
        "tree": _assert_tree(),
        "machine": _machine(),
        "workload": workload,
        "workload_sha256": hashlib.sha256(args.workload.read_bytes()).hexdigest(),
        "phases_requested": phases,
        "nice": os.nice(0),
        "notes": [
            "Measured on one machine with every process local; latency excludes any network.",
            "The derivative worker's vision model is scripted (fixed sleep, fixed answer, no network).",
            "PostgreSQL runs with fsync on, max_connections 100 and shared_buffers 128MB.",
        ],
    }
    timing = any(name != "chaos" for name in phases)
    record["idle_before_percent"] = idle_share()
    record["load_before"] = load_average()
    record["busiest_before"] = other_heavy_processes()
    if timing and (record["idle_before_percent"] or 0) < args.idle_gate:
        record["refused"] = (
            f"idle {record['idle_before_percent']}% is under the {args.idle_gate}% gate"
        )
        args.out.write_text(json.dumps(record, indent=1, sort_keys=True) + "\n")
        print(record["refused"], flush=True)
        return 3
    run_dir = Path(tempfile.mkdtemp(prefix="runtime-capacity-"))
    record["run_dir"] = str(run_dir)
    results: dict[str, Any] = {}
    try:
        with stack(workload, run_dir) as built:
            record["api_module_nice"] = subprocess.run(
                ["ps", "-o", "ni=", "-p", str(built.api.pid)], capture_output=True, text=True
            ).stdout.strip()
            for name in phases:
                print(f"phase {name} at {dt.datetime.now().strftime('%H:%M:%S')}", flush=True)
                saturating = bool(workload["phases"].get(name, {}).get("saturation"))
                if saturating and args.announce:
                    _announce(
                        args.announce,
                        f"saturation window START, phase {name}, load {load_average()}",
                    )
                started = time.monotonic()
                stopped = None
                try:
                    if name == "chaos":
                        results[name] = chaos(built, workload["chaos"])
                    elif workload["phases"][name]["kind"] == "sharing":
                        results[name] = asyncio.run(
                            phase_sharing(built, workload["phases"][name], name)
                        )
                    elif workload["phases"][name]["kind"] == "closed_reads":
                        results[name] = asyncio.run(phase_knee(built, workload["phases"][name]))
                    else:
                        results[name] = asyncio.run(
                            phase_mixed(built, workload["phases"][name], name)
                        )
                except BaseException as exc:
                    stopped = type(exc).__name__
                    raise
                finally:
                    # The window's end is announced however the phase ends, so a phase that
                    # stops early never leaves a saturation window open in the coordination file.
                    wall, load_now = round(time.monotonic() - started, 1), load_average()
                    if saturating and args.announce:
                        how = f"stopped early by {stopped}, " if stopped else ""
                        _announce(
                            args.announce,
                            f"saturation window END, phase {name}, {how}{wall} s, load {load_now}",
                        )
                results[name]["wall_seconds"] = wall
                results[name]["load_after"] = load_now
    finally:
        record["results"] = results
        record["idle_after_percent"] = idle_share()
        record["load_after"] = load_average()
        record["finished_at"] = dt.datetime.now(dt.UTC).isoformat(timespec="seconds")
        args.out.write_text(json.dumps(record, indent=1, sort_keys=True, default=str) + "\n")
        print(f"wrote {args.out}", flush=True)
    return 0


def _announce(path: Path, text: str) -> None:
    stamp = dt.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S %Z")
    with path.open("a") as handle:
        handle.write(f"\nR1 -> ROOT, {stamp}, {text}\n")


def main() -> int:
    if len(sys.argv) < 2 or sys.argv[1] not in ("run", "worker", "hold"):
        print(__doc__)
        return 2
    command, rest = sys.argv[1], sys.argv[2:]
    if command == "worker":
        return worker_main(rest)
    if command == "hold":
        return hold_main(rest)
    return run_main(rest)


if __name__ == "__main__":
    raise SystemExit(main())
