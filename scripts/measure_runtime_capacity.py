@dataclass
class Observed:
    """What the clients saw, kept per request so any later question can be answered from it."""

    reads: list[dict[str, Any]] = field(default_factory=list)
    uploads: list[dict[str, Any]] = field(default_factory=list)
    streams: list[dict[str, Any]] = field(default_factory=list)

    def summary(self) -> dict[str, Any]:
        admitted = [r["ms"] for r in self.reads if r["status"] == 200]
        refused = [r["ms"] for r in self.reads if r["status"] in (429, 503)]
        codes = Counter(f"{r['status']} {r.get('code') or ''}".strip() for r in self.reads)
        upload_codes = Counter(f"{u['status']} {u.get('code') or ''}".strip() for u in self.uploads)
        stream_codes = Counter(
            f"{attempt.get('status')} {attempt.get('code') or ''}".strip()
            for stream in self.streams
            for attempt in stream.get("attempts", [])
        )
        lags = [lag for s in self.streams for lag in s.get("lag_ms", [])]
        watched = [s for s in self.streams if s.get("watch")]
        return {
            "reads": {
                "sent": len(self.reads),
                "admitted_ms": spread(admitted),
                "refused_ms": spread(refused),
                "by_status": dict(sorted(codes.items())),
                "unexpected": sorted(
                    {c for c in codes if c.split()[0] not in ("200", "429", "503")}
                ),
            },
            "uploads": {
                "sent": len(self.uploads),
                "ms": spread([u["ms"] for u in self.uploads if u["status"] == 202]),
                "by_status": dict(sorted(upload_codes.items())),
                "unexpected": sorted(
                    {c for c in upload_codes if c.split()[0] not in ("202", "409", "429", "503")}
                ),
                "photos_accepted": sum(u.get("accepted", 0) for u in self.uploads),
                "parts_busy": sum(u.get("busy", 0) for u in self.uploads),
            },
            "streams": {
                "subscriptions": len(self.streams),
                "attempts_by_status": dict(sorted(stream_codes.items())),
                "event_lag_ms": spread(lags),
                "watched_batches": len(watched),
                "watched_reached_terminal": sum(1 for s in watched if s.get("terminal")),
                "duplicate_event_ids": sum(s.get("duplicates", 0) for s in self.streams),
                "foreign_events": sum(s.get("foreign", 0) for s in self.streams),
            },
        }


def jpeg(width: int, height: int, seed: int) -> bytes:
    """A distinct synthetic photograph: random blocks, so every upload is new bytes."""
    from PIL import Image, ImageDraw

    rng = random.Random(seed)
    image = Image.new("RGB", (width, height), tuple(rng.randrange(256) for _ in range(3)))
    draw = ImageDraw.Draw(image)
    for _ in range(24):
        x, y = rng.randrange(width), rng.randrange(height)
        draw.rectangle(
            [x, y, x + rng.randrange(1, width // 3), y + rng.randrange(1, height // 3)],
            fill=tuple(rng.randrange(256) for _ in range(3)),
        )
    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=85)
    return buffer.getvalue()


class Clients:
    """One ``httpx.AsyncClient`` per workspace, and the behaviours a phase combines."""

    def __init__(self, built: Stack, observed: Observed, photo: dict[str, int]) -> None:
        import httpx

        limits = httpx.Limits(max_connections=None, max_keepalive_connections=64)
        self.built = built
        self.observed = observed
        self.photo = photo
        self.clients = {
            grant.token: httpx.AsyncClient(
                base_url=built.base_url,
                headers={"Authorization": f"Bearer {grant.token}"},
                limits=limits,
                timeout=httpx.Timeout(60.0, connect=10.0),
            )
            for grant in built.grants
        }
        self.batches_of: dict[str, set[str]] = defaultdict(set)

    async def close(self) -> None:
        for client in self.clients.values():
            await client.aclose()

    async def read(self, token: str, path: str, phase: str) -> None:
        import httpx

        started = time.perf_counter()
        entry: dict[str, Any] = {"phase": phase, "path": path, "at": time.time()}
        try:
            response = await self.clients[token].get(path)
            entry["status"] = response.status_code
            if response.status_code != 200:
                with contextlib.suppress(ValueError):
                    entry["code"] = response.json().get("code")
        except httpx.HTTPError as exc:
            entry["status"] = 0
            entry["code"] = type(exc).__name__
        entry["ms"] = round((time.perf_counter() - started) * 1000, 3)
        self.observed.reads.append(entry)

    async def reads_open_loop(self, token: str, rate: float, until: float, phase: str) -> None:
        """Poisson arrivals at ``rate`` per second, each sent without waiting for the last."""
        rng = random.Random(f"{token}:{phase}")
        tasks = []
        paths = ["/formation?limit=20", "/operations/derivative-jobs"]
        index = 0
        while time.monotonic() < until:
            await asyncio.sleep(rng.expovariate(rate))
            tasks.append(asyncio.create_task(self.read(token, paths[index % 2], phase)))
            index += 1
        await asyncio.gather(*tasks)

    async def reads_closed_loop(self, token: str, until: float, phase: str) -> None:
        paths = ["/formation?limit=20", "/operations/derivative-jobs"]
        index = 0
        while time.monotonic() < until:
            await self.read(token, paths[index % 2], phase)
            index += 1

    async def upload(self, token: str, photos: int, phase: str) -> str | None:
        import httpx

        files = []
        for _ in range(photos):
            seed = next(_PHOTO_SEEDS)
            files.append(
                (
                    "files",
                    (
                        f"p{seed}.jpg",
                        jpeg(self.photo["width"], self.photo["height"], seed),
                        "image/jpeg",
                    ),
                )
            )
        started = time.perf_counter()
        entry: dict[str, Any] = {"phase": phase, "at": time.time(), "photos": photos}
        batch = None
        try:
            response = await self.clients[token].post("/intake", files=files)
            entry["status"] = response.status_code
            try:
                body = response.json()
            except ValueError:
                # An answer outside the problem shape (a plain-text 500 ended the first overload
                # attempt) is a result to record, not a reason to stop the phase.
                entry["code"] = "non_json"
                entry["body_head"] = response.text[:200]
            else:
                if response.status_code == 202:
                    batch = body["batch_id"]
                    self.batches_of[token].add(batch)
                    entry["batch_id"] = batch
                    entry["accepted"] = len(body["accepted"])
                    entry["busy"] = sum(1 for part in body["refused"] if part["reason"] == "busy")
                else:
                    entry["code"] = body.get("code")
                    entry["retry_after"] = response.headers.get("retry-after")
        except httpx.HTTPError as exc:
            entry["status"] = 0
            entry["code"] = type(exc).__name__
        entry["ms"] = round((time.perf_counter() - started) * 1000, 3)
        self.observed.uploads.append(entry)
        return batch

    async def uploads_every(
        self, token: str, every: float, photos: int, until: float, phase: str, watchers: list
    ) -> None:
        rng = random.Random(f"{token}:uploads:{phase}")
        await asyncio.sleep(rng.uniform(0, every))
        while time.monotonic() < until:
            batch = await self.upload(token, photos, phase)
            if batch is not None:
                watchers.append(asyncio.create_task(self.stream(token, batch, phase, watch=True)))
            await asyncio.sleep(every)

    async def stream(
        self,
        token: str,
        batch: str,
        phase: str,
        *,
        watch: bool = False,
        until: float | None = None,
        max_seconds: float = 600.0,
    ) -> dict[str, Any]:
        """Subscribe to ``batch`` and resume as a client should until its outcome or ``until``.

        Records every attempt's status, every event id (a repeat on one subscription is a
        duplicate), the lag between an event's server time and its arrival, and any event whose
        batch is not this one.
        """
        import httpx

        record: dict[str, Any] = {
            "phase": phase,
            "batch_id": batch,
            "watch": watch,
            "attempts": [],
            "events": [],
            "lag_ms": [],
            "duplicates": 0,
            "foreign": 0,
            "terminal": None,
        }
        self.observed.streams.append(record)
        seen: set[str] = set()
        token_since: str | None = None
        deadline = time.monotonic() + max_seconds
        wait = 1.0
        while time.monotonic() < deadline and (until is None or time.monotonic() < until):
            params = {"since": token_since} if token_since else None
            attempt: dict[str, Any] = {"at": time.time()}
            record["attempts"].append(attempt)
            try:
                async with self.clients[token].stream(
                    "GET",
                    f"/formation/{batch}",
                    params=params,
                    timeout=httpx.Timeout(None, connect=10.0),
                ) as response:
                    attempt["status"] = response.status_code
                    if response.status_code != 200:
                        body = await response.aread()
                        with contextlib.suppress(ValueError):
                            attempt["code"] = json.loads(body).get("code")
                        retry = response.headers.get("retry-after")
                        if response.status_code in (429, 503):
                            await asyncio.sleep(float(retry) if retry else wait)
                            continue
                        break
                    wait = 1.0
                    async for line in response.aiter_lines():
                        if until is not None and time.monotonic() >= until:
                            break
                        if not line.startswith("data: "):
                            continue
                        event = json.loads(line[len("data: ") :])
                        event_id = event["eventId"]
                        if event_id in seen:
                            record["duplicates"] += 1
                        seen.add(event_id)
                        if event["captureId"] != batch:
                            record["foreign"] += 1
                        record["events"].append(event_id)
                        record["lag_ms"].append(max(0.0, time.time() * 1000 - event["at"]))
                        token_since = event_id
                        if event["stageIndex"] >= 6:
                            record["terminal"] = event_id
                    if record["terminal"] is not None:
                        break
            except httpx.HTTPError as exc:
                attempt["status"] = 0
                attempt["code"] = type(exc).__name__
                await asyncio.sleep(wait)
                wait = min(wait * 2, 15.0)
        record["lag_ms"] = [round(value, 1) for value in record["lag_ms"]]
        return record


