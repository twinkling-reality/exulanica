"""A workspace's own things: the recipes, plans, kinds and looks it made or admitted (0159).

Here, above the pure ``exulanica.things`` package, because it holds a connection and a store.

Every piece is read by its own reader before it is kept, and again when it is read back:
- a body recipe by ``read_body_recipe``;
- a body plan by ``read_body_plan``;
- a thing kind by ``read_thing_kind``;
- a look by ``read_look``, with its container read by its profile's reader: the product's static
  glTF inspection, or the skinned reader against the plan's own tree.

A version is appended once and never changed. An edit is a new version, and a look is withdrawn by
a row of its own: every read passes a withdrawn look by unless it asks for one, as a kind naming
the look does, so the kind still reads while its look is no longer served. Rows stay inside their
workspace by row-level security. A key the product ships is never a row here: a shipped kind, plan
or look resolves first, so a row shadowing one would never be reached.

A look's container is held by digest in the workspace's own ``looks`` namespace of the
content-addressed store (:data:`exulanica.store.namespaces.LOOK_NAMESPACE`). An intake checks
everything before it writes anything: the documents and the container first, then, under the
workspace's lock, the caps and the versions held; only then are the bytes written, and the rows
naming them in the same transaction, so a row never names bytes the store lacks. Bytes whose rows
failed to commit stay, under their own digest, in the same workspace's namespace.

The intake paths:
- :meth:`ThingStore.keep_creature`: a creature drafted from words, its recipe, plan, sketch and
  kind in one transaction.
- :meth:`ThingStore.admit_look`: a look made elsewhere, generated by route C or imported (a
  traveller's own look from an outside game, built at a deployment), read by
  :func:`read_admission` and then by its intake's own ``admit`` check.
  - Its label and its origin's words are held to the line rule.
  - A share-alike licence is kept only with the credit it asks: the attribution, the authors and
    the licence's address, which the table requires as well.

:func:`admitted_look` and :func:`admitted_look_by_digest` are the reads a world's look choice asks:
a look this workspace holds at exactly the reference or digest it names, read again and not
withdrawn, or None. This module reaches the content store only through the store's interface and
imports no evidence module, so the door may ask them for a crossing's look within its import
contract.
"""

