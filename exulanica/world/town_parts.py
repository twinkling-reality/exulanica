"""The buildings a made town was made with, and a person's changes to them: removed, taller, lower.

A made town is generated by the city grammar from its receipt (:func:`~exulanica.world.
generated_worlds.town_records`). A building is a ``city.massing`` record with the facades, ground
bays, entrances, vitrines, interior backings, premises, rooftop objects and materials that follow
from it and from its neighbours. A person's change to one is never an edit of those records: the
city grammar's massing stage takes it (:func:`~exulanica.grammar.grammars.city.city_grammar_with`)
and every later stage runs as it does, so a neighbour's party wall follows the building beside it
by the grammar's own rule (:func:`~exulanica.world.generated_worlds.town_records_with`).

A change is stored as a site part's is (:mod:`exulanica.world.site_parts`): an element override
named ``part:<building identity>``, suppressed for a removal, or stating ``storeys``. A town's
building is never moved: it stands on its lot.

This module reads the records and words; it decides nothing the grammar decides. A storey count
outside a lot's range is the grammar's refusal (:class:`~exulanica.grammar.grammars.city.
generation.massing.BuildingStoreysRefused`), said here in words. Who lives or works in a building
is read from its premises (each names its building) and the society's people.

Pure: no connection and no store.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from exulanica.grammar.grammars.city.generation.massing import (
    BuildingChange,
    BuildingStoreysRefused,
)
from exulanica.grammar.grammars.city.generation.stage import entry
from exulanica.grammar.grammars.city.massing import MassingRecord
from exulanica.grammar.grammars.city.premises import PremisesRecord
from exulanica.world.site_parts import PartChange, PartChangeRefused, people_in

__all__ = [
    "TownBuilding",
    "building_changes",
    "people_of_building",
    "premises_taken",
    "storeys_refusal",
    "town_buildings",
]


@dataclass(frozen=True, slots=True)
class TownBuilding:
    """A building of a made town as it stands: its identity, what it is and its words, its
    storeys, and the premises it holds."""

    identity: str
    typology: str
    label: str
    storeys: int
    premises: tuple[str, ...]

    def document(self) -> dict[str, Any]:
        return {
            "part_id": self.identity,
            "kind": "building",
            "typology": self.typology,
            "label": self.label,
            "storeys": self.storeys,
            "premises": list(self.premises),
        }


def _label(typology: str) -> str:
    return str(entry("typology", typology).get("label") or typology.replace("_", " "))


def town_buildings(records: Sequence[object]) -> tuple[TownBuilding, ...]:
    """Every building of a town's records, in their order, with the premises each holds."""
    premises: dict[str, list[str]] = {}
    for record in records:
        if isinstance(record, PremisesRecord):
            premises.setdefault(record.building_identity, []).append(record.identity)
    return tuple(
        TownBuilding(
            identity=record.identity,
            typology=record.typology,
            label=_label(record.typology),
            storeys=record.storeys,
            premises=tuple(sorted(premises.get(record.identity, ()))),
        )
        for record in records
        if isinstance(record, MassingRecord)
    )


def building_changes(changes: Sequence[PartChange]) -> dict[str, BuildingChange]:
    """A version's part changes as the city grammar's building changes; a move is refused by name:
    a town's building stands on its lot."""
    found = {}
    for change in changes:
        if change.centre_mm is not None:
            raise PartChangeRefused(
                "part_not_changeable",
                {"part_id": change.identity},
                "A town's building stands on its lot: it is not moved.",
            )
        found[change.identity] = BuildingChange(removed=change.removed, storeys=change.storeys)
    return found


def storeys_refusal(refused: BuildingStoreysRefused) -> PartChangeRefused:
    """The grammar's refusal of a storey count, as a person reads it."""
    label = _label(refused.typology).lower()
    where = {
        "part_id": refused.identity,
        "storeys": refused.storeys,
        "fewest": refused.fewest,
        "most": refused.most,
    }
    if refused.storeys > refused.most:
        words = f"Not taller: a {label} here has at most {refused.most} storeys."
    else:
        words = (
            f"Not lower: a {label} here has at least {refused.fewest} "
            f"{'storey' if refused.fewest == 1 else 'storeys'}."
        )
    return PartChangeRefused("part_storeys_refused", where, words)


def people_of_building(
    state: Mapping[str, Any], premises: Sequence[str]
) -> list[tuple[str | None, str]]:
    """Who lives or works in any of a building's premises, as ``(name, "lives" | "works")``: a
    society of things names a premises ``city.premises:<identity>``, a living town
    ``premises:<identity>`` (:func:`~exulanica.world.site_parts.people_in`)."""
    return people_in(
        state,
        subjects={f"city.premises:{identity}" for identity in premises},
        destinations={f"premises:{identity}" for identity in premises},
    )


def premises_taken(
    before: Sequence[object], after: Sequence[object], building: str
) -> tuple[str, ...]:
    """The premises of ``building`` the changed records no longer hold: what lowering it to one
    storey, or removing it, takes away."""
    held = {
        record.identity
        for record in after
        if isinstance(record, PremisesRecord) and record.building_identity == building
    }
    return tuple(
        sorted(
            record.identity
            for record in before
            if isinstance(record, PremisesRecord)
            and record.building_identity == building
            and record.identity not in held
        )
    )
