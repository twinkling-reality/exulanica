"""The tools that make a world from a person's words, as one catalog a chooser reads.

A world is generated by a tool: a composer with the drafter that turns words into what that
composer takes. ``assets/catalogs/world-tools/world-tool.v1.json`` states each one by its composer
key and version, the drafter that feeds it, and in plain words what it can make and what it
cannot. Those words are all a model is shown when it chooses the tool for a description
(:mod:`exulanica.selection.tool_choosing`), so a further generator is one more entry here and no
change to the choosing. Exactly one entry is the tool taken where the choice is unsure.
"""

from __future__ import annotations

import functools
from dataclasses import dataclass
from pathlib import Path
from typing import Final, cast

from exulanica.grammar.catalogs import (
    CatalogSchema,
    FieldValue,
    integer_field,
    load_catalog,
    text_field,
)
from exulanica.grammar.errors import CatalogError
from exulanica.grammar.records import KEY_PATTERN

__all__ = ["CATALOG_PATH", "DRAFTERS", "WorldTool", "tool_for_unsure", "world_tools"]

CATALOG_PATH: Final = (
    Path(__file__).resolve().parents[2]
    / "assets"
    / "catalogs"
    / "world-tools"
    / "world-tool.v1.json"
)
#: The drafters a tool may be fed by: the town's specification drafter and the kind drafter.
DRAFTERS: Final = ("kind", "specification")
_WORDS_MAXIMUM: Final = 400


def _composer_key(where: str, value: object) -> FieldValue:
    if type(value) is not str or not all(KEY_PATTERN.fullmatch(part) for part in value.split("-")):
        raise CatalogError(f"{where} is a composer key, got {value!r}")
    return value


def _drafter(where: str, value: object) -> FieldValue:
    if value not in DRAFTERS:
        raise CatalogError(f"{where} is one of {list(DRAFTERS)}, got {value!r}")
    return cast(str, value)


def _words(where: str, value: object) -> FieldValue:
    text = text_field(where, value)
    if "\n" in cast(str, text) or len(cast(str, text)) > _WORDS_MAXIMUM:
        raise CatalogError(f"{where} is one line of at most {_WORDS_MAXIMUM} characters")
    return text


_SCHEMA: Final = CatalogSchema(
    "world-tool",
    1,
    (
        ("composer_key", _composer_key),
        ("composer_version", integer_field(1, 9999)),
        ("drafter", _drafter),
        ("unsure", integer_field(0, 1)),
        ("makes", _words),
        ("cannot", _words),
        ("reason", text_field),
    ),
)


@dataclass(frozen=True, slots=True)
class WorldTool:
    """One tool: its key, the composer it drives, its drafter, and what it makes in words."""

    key: str
    composer_key: str
    composer_version: int
    drafter: str
    makes: str
    cannot: str
    unsure: bool


@functools.cache
def world_tools(path: Path = CATALOG_PATH) -> tuple[WorldTool, ...]:
    """Every tool the catalog states, by key; refused unless exactly one is taken when unsure and
    no two drive one composer."""
    catalog = load_catalog(path, _SCHEMA)
    tools = []
    for entry in sorted(catalog.entries, key=lambda entry: entry.key):
        values = dict(entry.values)
        tools.append(
            WorldTool(
                key=entry.key,
                composer_key=str(values["composer_key"]),
                composer_version=cast(int, values["composer_version"]),
                drafter=str(values["drafter"]),
                makes=str(values["makes"]),
                cannot=str(values["cannot"]),
                unsure=values["unsure"] == 1,
            )
        )
    if sum(tool.unsure for tool in tools) != 1:
        raise CatalogError(f"{path.name} names exactly one tool taken where the choice is unsure")
    if len({tool.composer_key for tool in tools}) != len(tools):
        raise CatalogError(f"{path.name} names each composer once")
    return tuple(tools)


def tool_for_unsure(path: Path = CATALOG_PATH) -> WorldTool:
    """The tool taken where no tool was chosen."""
    return next(tool for tool in world_tools(path) if tool.unsure)
