"""The world kinds the product ships: kind documents under ``assets/catalogs/world-kinds/library``.

Each file is named ``<kind>.v<version>.json`` and is either

* a **world kind** (``exulanica.world-kind/v1``) the site grammar generates, read and held to
  stage A as every kind is (:func:`~exulanica.world.kinds.document.read_kind`); a test holds every
  shipped kind to stage B as well, so the library never offers a kind whose worlds people could not
  live in; or
* an **adapter** (``exulanica.world-kind-adapter/v1``) for a generator that is not the site grammar:
  the town, generated by the city grammar from the world specification's presets and values. The
  adapter names the specification schema and the preset catalog by the SHA-256 of their files and
  copies neither, so the town's values, ranges and presets have one source, and a changed file
  refuses the adapter by name until it is revised; it lists the town's parts in the same words and
  look roles every kind uses, so the interface, the Companion and the style packs read one
  vocabulary. Making a town from the adapter is making it from its preset, through the same gate and
  composer, so no town's receipt or digest depends on the adapter.

A shipped kind may start on a setting (``assets/catalogs/landscape-settings``): its worlds are made
on that setting's landscape wherever their making names no land, landscape or support of its own
(:func:`starter_landscape`). Only the shipped document itself starts there; a workspace's kind of
the same key and version is its own kind and starts on open ground.
"""

from __future__ import annotations

import functools
import hashlib
import json
import re
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final

from exulanica.grammar.documents import read_json
from exulanica.grammar.errors import CatalogError
from exulanica.world.kinds.catalogs import CATALOG_DIRECTORY
from exulanica.world.kinds.document import KindDocument, read_kind

if TYPE_CHECKING:
    from exulanica.grammar.landscape import LandscapeSetting
    from exulanica.world.models import StylePackBinding

__all__ = [
    "ADAPTER_PROFILE",
    "LIBRARY_DIRECTORY",
    "TownAdapter",
    "shipped_kinds",
    "starter_landscape",
    "starter_look",
    "starter_setting_parts",
    "town_adapter",
]

LIBRARY_DIRECTORY: Final = CATALOG_DIRECTORY / "library"
ADAPTER_PROFILE: Final = "exulanica.world-kind-adapter/v1"
_NAME: Final = re.compile(r"([a-z][a-z0-9_]{0,31})\.v([1-9][0-9]{0,3})\.json")
_RECIPES: Final = Path(__file__).resolve().parents[3] / "assets" / "catalogs" / "world-recipes"


@dataclass(frozen=True, slots=True)
class TownAdapter:
    """The town as a world kind: the city grammar's generator over the world specification."""

    document: Mapping[str, Any]
    sha256: str

    @property
    def kind(self) -> str:
        return str(self.document["kind"])

    @property
    def version(self) -> int:
        return int(self.document["version"])


def _file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read_adapter(path: Path) -> TownAdapter:
    document = read_json(path)
    if not isinstance(document, dict) or document.get("profile") != ADAPTER_PROFILE:
        raise CatalogError(f"{path.name} is not a world kind adapter")
    for field, stated in (
        ("specification", document["specification"]),
        ("presets", document["presets"]),
    ):
        source = _RECIPES / f"{stated['name']}.json"
        if not source.is_file() or _file_sha256(source) != stated["sha256"]:
            raise CatalogError(
                f"{path.name} names {field} {stated['name']} by a digest its file no longer has; "
                "revise the adapter with the file"
            )
    if (document["generator"]["key"], document["kind"]) != ("city-grammar-town", "town"):
        raise CatalogError(f"{path.name}: the one adapter is the town's")
    canonical = json.dumps(document, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return TownAdapter(document, hashlib.sha256(canonical.encode("utf-8")).hexdigest())


@functools.cache
def _library() -> tuple[tuple[KindDocument, ...], TownAdapter | None]:
    kinds: list[KindDocument] = []
    town: TownAdapter | None = None
    for path in sorted(LIBRARY_DIRECTORY.glob("*.json")):
        named = _NAME.fullmatch(path.name)
        if named is None:
            raise CatalogError(f"{path.name} is not named <kind>.v<version>.json")
        raw = read_json(path)
        if isinstance(raw, dict) and raw.get("profile") == ADAPTER_PROFILE:
            town = _read_adapter(path)
            stated = (town.kind, town.version)
        else:
            kind = read_kind(raw)
            kinds.append(kind)
            stated = (kind.kind, kind.version)
        if stated != (named.group(1), int(named.group(2))):
            raise CatalogError(f"{path.name} states kind {stated[0]} version {stated[1]}")
    return tuple(kinds), town


def shipped_kinds() -> tuple[KindDocument, ...]:
    """Every world kind the product ships, read once, in file order."""
    return _library()[0]


def town_adapter() -> TownAdapter:
    """The town's adapter, refused by name when the library holds none."""
    town = _library()[1]
    if town is None:
        raise CatalogError("the world kind library holds no town adapter")
    return town


def _starting(kind: KindDocument) -> LandscapeSetting | None:
    """The setting the settings catalog starts ``kind`` on, for a shipped kind's own document only
    (its digest the shipped one's); None for every other kind, a workspace's of the same key
    included."""
    from exulanica.grammar.landscape import starting_setting

    shipped = next(
        (k for k in shipped_kinds() if (k.kind, k.version) == (kind.kind, kind.version)), None
    )
    if shipped is None or shipped.sha256 != kind.sha256:
        return None
    return starting_setting(kind.kind, kind.version)


def starter_landscape(kind: KindDocument) -> dict[str, Any] | None:
    """The landscape a world of ``kind`` is made on when its making names none: its setting's,
    as :func:`_starting` finds it; None where it starts on none."""
    setting = _starting(kind)
    return None if setting is None else setting.landscape()


def starter_setting_parts(kind: KindDocument) -> dict[str, str] | None:
    """The setting parts a world of ``kind`` made on its setting is drawn in, a part's key for each
    axis its setting names; None where it starts on no setting or its setting names none. Refuses
    (:class:`CatalogError`) a part the setting parts catalog does not hold."""
    from exulanica.world.world_settings import setting_parts

    setting = _starting(kind)
    if setting is None or not setting.setting_parts:
        return None
    held = setting_parts().parts
    for axis, part in setting.setting_parts:
        if (axis, part) not in held:
            raise CatalogError(
                f"setting {setting.key} names the {axis} part {part!r}, which the setting "
                "parts catalog does not hold"
            )
    return dict(setting.setting_parts)


def starter_look(kind: KindDocument) -> StylePackBinding | None:
    """What a world of ``kind`` made on its setting is drawn in: the host's default look with the
    setting its setting's parts compose for that look, as a drafted world's taken parts are; None
    where its setting names no parts or they change nothing of that look."""
    from exulanica.world.models import StylePackBinding
    from exulanica.world.style_pack_library import style_pack_context, style_pack_library
    from exulanica.world.world_settings import bound_setting

    parts = starter_setting_parts(kind)
    if parts is None:
        return None
    library = style_pack_library()
    pack = library.default_pack
    chain = library.chain(pack.manifest_sha256)
    setting = None if chain is None else bound_setting(chain, style_pack_context(), chosen=parts)
    if setting is None:
        return None
    return StylePackBinding(pack.pack_id, pack.version, pack.manifest_sha256, setting=setting)
