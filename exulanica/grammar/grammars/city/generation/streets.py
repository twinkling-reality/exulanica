"""The streets generator: a lattice of straight streets, its blocks, curbs, lanes and junctions.

**The layout rule, stage version 2.** Inside the district's rectangle, streets run on two axes.
Streets along x (east-west) lie ``block_depth_mm`` apart and the one through the district's
middle is the high street; streets along y (north-south) lie ``block_length_mm`` apart, placed so
the district's middle falls half way between two of them. A street line is laid out only where its
widest possible cross-section (carriageway, kerb and footway at their declared maxima) stays inside
the district. Streets along x run the district's whole width; streets along y run between the
southernmost and northernmost streets along x and end there in T junctions. Every centreline is one
straight piece between two nodes, so no piece is longer than the district, and a district is at
most 2048 m across.

**Hierarchy and names.** The high street is ``high_street``; every other street is
``local_street``. Each street takes its hierarchy's fewest lanes, half in each direction, the side
of the road the district states deciding which half is which. Names come from the street-name
catalog entries that suit the hierarchy, drawn without repeating.

**Faces.** The streets divide the district into faces: a block between four streets, an open face
where the district's edge closes it, and the two outer faces beyond the first and last streets
along x. Walking a face counter-clockwise gives each curb its follower: a left turn is a corner of
the face's ``corner_radius_mm``, a straight join (where a street ends in a T on the far side) has
radius 0, and the district's edge ends the walk. Every curb of one face shares that face's kerb
height, kerb width, footway width and crossfall, each derived once per face and narrowed to the
ranges of the busiest street hierarchy the face touches, since a footway does not narrow and a kerb
does not change height as a person turns a corner; a block's frontage line is then its kerb lines
moved kerb and footway out, and its ring's corners are its corners' frontage corners exactly.

**Cross-sections.** A carriageway is its lanes and two gutters, centred on the crown line. One
gutter width runs along a whole street, so this version reads ``gutter_width_mm`` bound for the
district or the city and refuses to derive it face by face. Lane width, camber and speed limit are
district values, derived once and narrowed to every hierarchy the district's streets have.
Street dimensions derive on a 50 mm module, so every carriageway is an even number of millimetres
and its crown lies on a whole millimetre. The crown is at the datum; a kerb line lies the camber's
fall below it; a lane's centreline lies on the camber plane.

**Heights.** A kerb line is ``floor(W / 2 * camber / 10**6)`` below the crown, a curb's frontage is
its kerb height and footway rise above its kerb line, and a block's grade is the highest frontage
round it, so no lot lies below the footway it meets.

**Crossings.** Every junction leg carries one, at the near end of its straight kerb run, so it
meets a dropped kerb on both sides and clears the corner arcs. It is ``crossing_width_mm`` wide and
leaves ``dropped_kerb_upstand_mm`` of kerb standing. A leg whose straight run holds only one
crossing carries the one nearer its start node. Every crossing is a zebra: a signalised one names a
plan in traffic's catalog, which the city grammar does not read.

**Not generated by this version,** and each says why: road markings, which no published texture set
dresses; signals, whose plan catalog the city does not read; lane connections and parking. Lane
markings are ``none``, since no paint is generated.

**Junctions.** Every approach states the tightest turn it must admit: the widest turning radius the
lane-use catalog states for the uses of that segment's lanes. The catalog takes those from traffic's
vehicle classes and names that catalog by digest; this stage reads the city's catalog only.

A node where three or four segments meet is a junction. A junction on the high
street gives its high street legs priority and its other legs a stop; any other junction gives the
street that continues through it priority and the street that ends there a stop. Its extent is the
fill the corner rule states (:func:`~exulanica.grammar.grammars.city.corners.junction_fill_box`).
"""

